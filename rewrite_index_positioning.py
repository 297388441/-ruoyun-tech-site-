def main():
    with io.open(PATH, "r", encoding="utf-8") as f:
        html = f.read()
    miss = 0
    for i, (old, new, *rest) in enumerate(REPL):
        ra = rest[0] if rest else False
        cnt = html.count(old)
        if cnt == 0:
            print(f"[未命中] #{i+1}: {old[:40]}")
            miss += 1
            continue
        if ra and cnt > 1:
            html = html.replace(old, new)
            print(f"[替换ALL] #{i+1}: 命中 {cnt} 处")
        else:
            if cnt > 1 and not ra:
                print(f"[警告] #{i+1}: 命中 {cnt} 处但未设 replace_all，仅改第一处: {old[:40]}")
            html = html.replace(old, new, 1)
            print(f"[替换1] #{i+1}: 命中 {cnt} 处")
    if miss:
        print(f"\n共 {miss} 处未命中，已中止写入（避免半成品）。")
        sys.exit(1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(html)
    print("\n✅ index.html 定位重排完成，全部命中写入。")

if __name__ == "__main__":
    main()
