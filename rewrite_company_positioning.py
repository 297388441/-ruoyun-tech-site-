def main():
    with io.open(PATH, "r", encoding="utf-8") as f:
        html = f.read()
    miss = 0
    for i, (old, new, *rest) in enumerate(REPL):
        ra = rest[0] if rest else False
        cnt = html.count(old)
        if cnt == 0:
            print(f"[未命中] #{i+1}: {old[:40]}")
            miss += 1
            continue
        html = html.replace(old, new) if (ra or cnt == 1) else html.replace(old, new, 1)
        print(f"[替换] #{i+1}: 命中 {cnt} 处")
    if miss:
        print(f"\n共 {miss} 处未命中，已中止写入。")
        sys.exit(1)
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(html)
    print("\n✅ company.html 定位重排完成。")

if __name__ == "__main__":
    main()
